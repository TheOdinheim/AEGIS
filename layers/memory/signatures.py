"""
L4 Tier 2 — Signature Database & Clonal Selection Signature Generator

Stores regex patterns and lightweight classifier weights generated by the
Clonal Selection process. Each signature includes performance tracking
(true positive rate, false positive rate, match count). Signatures with
degrading performance are automatically deprecated.

Implements biological clonal selection for automated signature optimization:
  1. Hypermutation — Generate 10-20 candidate regex patterns from attack text
  2. Affinity Testing — Score each candidate against positive (known attacks)
     and negative (benign business prompts) validation sets
  3. Selection & Amplification — Promote top candidates exceeding affinity
     threshold to the signature database for L2 innate fast-path detection

When adaptive catches a novel attack, clonal selection generates optimized
regex patterns so similar future attacks are caught in <5ms by L2 innate.

ASSUMED-BREACH POSTURE: Generated signatures could be deliberately weak
if the source attack was crafted to produce ineffective patterns. Every
signature tracks provenance (source indicator_id), TPR, FPR, and match
count. Signatures with FPR exceeding threshold after N matches are
automatically deprecated. Affinity testing filters out patterns matching
benign traffic before promotion.
"""

from __future__ import annotations

import json
import logging
import re
import string
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field

from aegis.config import MemoryConfig

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Signature Entry — Data Model
# ---------------------------------------------------------------------------


class SignatureEntry(BaseModel):
    """A single signature in the database with performance tracking."""
    signature_id: str = Field(default_factory=lambda: f"sig-{uuid.uuid4().hex[:8]}")
    pattern: str = Field(description="Regex pattern string")
    category: str = Field(default="prompt_injection")
    description: str = Field(default="")
    source_indicator_id: str = Field(
        default="", description="ThreatIndicator that spawned this via clonal selection",
    )
    affinity_score: float = Field(default=0.0, ge=0.0, le=1.0)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    deprecated: bool = Field(default=False)
    tp_rate: float = Field(default=1.0, ge=0.0, le=1.0)
    fp_rate: float = Field(default=0.0, ge=0.0, le=1.0)
    match_count: int = Field(default=0, ge=0)
    false_positive_count: int = Field(default=0, ge=0)
    avg_latency_ms: float = Field(default=0.0, ge=0.0)

    @property
    def observed_fpr(self) -> float:
        """Observed false positive rate from recorded matches."""
        if self.match_count == 0:
            return 0.0
        return self.false_positive_count / self.match_count

    def record_match(self, is_false_positive: bool = False) -> None:
        """Record a match event for deprecation tracking."""
        self.match_count += 1
        if is_false_positive:
            self.false_positive_count += 1


# ---------------------------------------------------------------------------
# Signature Store — Database Layer
# ---------------------------------------------------------------------------


class SignatureStore:
    """JSON-backed signature store with performance tracking and auto-deprecation.

    Manages regex signatures generated by Clonal Selection. Provides
    match() for scanning text against all active signatures, and
    add()/deprecate()/deprecation_check() for lifecycle management.

    PostgreSQL dual-write: When a session_factory is set, all add/deprecate
    operations are also persisted to the ``signatures`` table. JSON file
    remains the primary store; PostgreSQL provides durability.
    """

    def __init__(
        self,
        store_file: str | Path | None = None,
        config: MemoryConfig | None = None,
        session_factory: Any | None = None,
    ):
        self._config = config or MemoryConfig()
        self._signatures: list[SignatureEntry] = []
        self._compiled: dict[str, re.Pattern] = {}
        self._session_factory = session_factory
        if store_file is not None:
            self.load(store_file)

    @property
    def session_factory(self) -> Any | None:
        return self._session_factory

    @session_factory.setter
    def session_factory(self, value: Any | None) -> None:
        self._session_factory = value

    @property
    def size(self) -> int:
        return len(self._signatures)

    @property
    def active_count(self) -> int:
        return sum(1 for s in self._signatures if not s.deprecated)

    def load(self, store_file: str | Path) -> int:
        """Load signatures from a JSON file."""
        path = Path(store_file)
        if not path.exists():
            return 0
        with path.open("r") as f:
            data = json.load(f)
        for entry in data.get("signatures", []):
            sig = SignatureEntry(**entry)
            self._signatures.append(sig)
            self._compile_pattern(sig)
        return len(self._signatures)

    def _compile_pattern(self, sig: SignatureEntry) -> None:
        """Compile and cache a signature's regex pattern."""
        try:
            self._compiled[sig.signature_id] = re.compile(sig.pattern, re.IGNORECASE)
        except re.error:
            logger.warning("Invalid regex in signature %s: %s", sig.signature_id, sig.pattern)

    def add(
        self,
        pattern: str,
        category: str = "prompt_injection",
        description: str = "",
        source_indicator_id: str = "",
        affinity_score: float = 0.0,
        tp_rate: float = 0.0,
        fp_rate: float = 0.0,
    ) -> SignatureEntry:
        """Add a new signature to the store."""
        sig = SignatureEntry(
            pattern=pattern,
            category=category,
            description=description,
            source_indicator_id=source_indicator_id,
            affinity_score=affinity_score,
            tp_rate=tp_rate,
            fp_rate=fp_rate,
        )
        self._signatures.append(sig)
        self._compile_pattern(sig)
        # PostgreSQL dual-write
        self._pg_upsert_signature(sig)
        return sig

    def get_all(self, include_deprecated: bool = False) -> list[SignatureEntry]:
        """Return all signatures, optionally including deprecated ones."""
        if include_deprecated:
            return list(self._signatures)
        return [s for s in self._signatures if not s.deprecated]

    def get_by_id(self, signature_id: str) -> SignatureEntry | None:
        """Retrieve a signature by ID."""
        for s in self._signatures:
            if s.signature_id == signature_id:
                return s
        return None

    def get_by_source(self, indicator_id: str) -> list[SignatureEntry]:
        """Return signatures generated from a specific threat indicator."""
        return [s for s in self._signatures if s.source_indicator_id == indicator_id]

    def match(self, text: str) -> list[SignatureEntry]:
        """Match text against all active signatures. Returns matched entries."""
        matches = []
        for sig in self._signatures:
            if sig.deprecated:
                continue
            compiled = self._compiled.get(sig.signature_id)
            if compiled and compiled.search(text):
                matches.append(sig)
        return matches

    def deprecate(self, signature_id: str) -> bool:
        """Deprecate a signature (poor performance or manual override)."""
        for sig in self._signatures:
            if sig.signature_id == signature_id:
                sig.deprecated = True
                # PostgreSQL dual-write
                self._pg_update_signature_status(
                    signature_id, "deprecated",
                    match_count=sig.match_count,
                    fpr=sig.observed_fpr,
                )
                return True
        return False

    def deprecation_check(self) -> list[str]:
        """Auto-deprecate signatures exceeding FPR threshold.

        Only evaluates signatures with sufficient match count to avoid
        premature deprecation from small sample sizes.

        Returns list of deprecated signature IDs.
        """
        deprecated = []
        min_matches = self._config.signature_deprecation_min_matches
        max_fpr = self._config.signature_max_fpr

        for sig in self._signatures:
            if sig.deprecated:
                continue
            if sig.match_count < min_matches:
                continue
            if sig.observed_fpr > max_fpr:
                sig.deprecated = True
                deprecated.append(sig.signature_id)
                logger.info(
                    "Auto-deprecated signature %s: observed FPR=%.3f > threshold=%.3f "
                    "(matches=%d, FP=%d)",
                    sig.signature_id, sig.observed_fpr, max_fpr,
                    sig.match_count, sig.false_positive_count,
                )
                # PostgreSQL dual-write
                self._pg_update_signature_status(
                    sig.signature_id, "deprecated",
                    match_count=sig.match_count,
                    fpr=sig.observed_fpr,
                )
        return deprecated

    def _pg_upsert_signature(self, sig: SignatureEntry) -> None:
        """Fire-and-forget PostgreSQL upsert for a signature."""
        if self._session_factory is None:
            return
        try:
            import asyncio
            from aegis.services.audit_logger import upsert_signature
            asyncio.create_task(upsert_signature(
                session_factory=self._session_factory,
                signature_id=sig.signature_id,
                pattern_type="regex",
                pattern_text=sig.pattern,
                source_indicator_id=sig.source_indicator_id or None,
                affinity_score=sig.affinity_score,
                tpr=sig.tp_rate,
                fpr=sig.fp_rate,
                status="deprecated" if sig.deprecated else "active",
                match_count=sig.match_count,
            ))
        except (RuntimeError, ImportError):
            pass

    def _pg_update_signature_status(
        self, signature_id: str, new_status: str,
        match_count: int | None = None, fpr: float | None = None,
    ) -> None:
        """Fire-and-forget PostgreSQL status update for a signature."""
        if self._session_factory is None:
            return
        try:
            import asyncio
            from aegis.services.audit_logger import update_signature_status
            asyncio.create_task(update_signature_status(
                session_factory=self._session_factory,
                signature_id=signature_id,
                new_status=new_status,
                match_count=match_count,
                fpr=fpr,
            ))
        except (RuntimeError, ImportError):
            pass

    def save(self, store_file: str | Path) -> None:
        """Persist signatures to a JSON file."""
        path = Path(store_file)
        path.parent.mkdir(parents=True, exist_ok=True)
        data = {
            "signatures": [s.model_dump(mode="json") for s in self._signatures]
        }
        with path.open("w") as f:
            json.dump(data, f, indent=2, default=str)


