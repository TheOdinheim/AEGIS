"""
Canary Injection System — Temporal threat detection via known-answer probes.

Injects canary queries with known expected answers through the full AEGIS
pipeline. Response divergence from expected answers indicates model behavioral
drift, poisoning, or compromise.

ASSUMED-BREACH POSTURE: Canary queries must be indistinguishable from real
traffic. If an attacker can identify canaries, they can selectively respond
correctly to canaries while behaving maliciously on real queries. Canary
queries are drawn from a diverse pool, injected with randomized timing, and
flagged internally only AFTER authentication (so they traverse L2/L3 like
real traffic). The canary flag is never exposed in responses or logs.
"""

from __future__ import annotations

import asyncio
import json
import logging
import random
import time
import uuid
from collections import deque
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Coroutine

import numpy as np

logger = logging.getLogger(__name__)

