"""
AdaptiveAnalysisResult & AdaptiveAnalysisReport — L3 Adaptive output contracts.

Each of the five adaptive analyzers (injection classifier, semantic similarity,
behavioral baseline, multi-turn sequence, DCA aggregator) returns an
AdaptiveAnalysisResult. The layer aggregates them into an AdaptiveAnalysisReport.

ASSUMED-BREACH POSTURE: These results are produced by ML models that could
themselves be compromised. A poisoned DeBERTa classifier could return benign
scores for specific attack patterns (sleeper agent behavior). A corrupted
FAISS index could fail to match known threats. The Policy Engine (L6) never
relies solely on adaptive results — it fuses them with innate results and
applies independent policy rules. The DCA aggregator's MCAV score is one
input to the decision, not the decision itself.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum

from pydantic import BaseModel, Field

from aegis.models.scan_result import ThreatCategory


class AnalyzerType(str, Enum):
    """Identifier for each adaptive analyzer module."""
    INJECTION_CLASSIFIER = "injection_classifier"
    SEMANTIC_SIMILARITY = "semantic_similarity"
    BEHAVIORAL_BASELINE = "behavioral_baseline"
    MULTI_TURN_SEQUENCE = "multi_turn_sequence"
    DANGER_SIGNAL_AGGREGATOR = "danger_signal_aggregator"


class SignalType(str, Enum):
    """DCA signal categories per Danger Theory."""
    PAMP = "pamp"        # Confirmed threat indicator
    DANGER = "danger"    # Potential problem indicator
    SAFE = "safe"        # Normal operation indicator


class DCASignal(BaseModel):
    """A single signal fed into the Dendritic Cell Algorithm.

    The DCA fuses PAMPs, danger signals, and safe signals from all analyzers
    plus system telemetry to produce the MCAV score.
    """
    signal_type: SignalType = Field(description="PAMP, danger, or safe")
    source: str = Field(description="Which analyzer or telemetry source produced this")
    value: float = Field(
        ge=0.0, le=1.0, description="Signal strength 0.0-1.0"
    )
    description: str = Field(default="", description="Human-readable explanation")


class AdaptiveAnalysisResult(BaseModel):
    """Output from a single adaptive analyzer.

    Similar structure to ScanResult but includes ML-specific fields like
    embedding vectors, similarity scores, and DCA signals.

    Fields:
        analyzer_id: Which analyzer produced this result.
        is_threat: Whether this analyzer detected a threat.
        confidence: Confidence score 0.0-1.0.
        threat_category: MITRE ATLAS tactic or AEGIS category.
        details: Analyzer-specific details (model output, similarity score, etc.).
        dca_signals: DCA signals generated by this analyzer for the aggregator.
        latency_ms: Analyzer execution time in milliseconds.
    """
    analyzer_id: AnalyzerType = Field(description="Analyzer identifier")
    is_threat: bool = Field(description="Whether a threat was detected")
    confidence: float = Field(
        ge=0.0, le=1.0, description="Confidence score 0.0-1.0"
    )
    threat_category: ThreatCategory = Field(
        default=ThreatCategory.UNKNOWN,
        description="MITRE ATLAS tactic or AEGIS category",
    )
    details: dict[str, object] = Field(
        default_factory=dict,
        description="Analyzer-specific details (similarity score, PSI value, etc.)",
    )
    dca_signals: list[DCASignal] = Field(
        default_factory=list,
        description="DCA signals for the Danger Signal Aggregator",
    )
    latency_ms: float = Field(
        ge=0.0, description="Analyzer execution time in milliseconds"
    )


class AdaptiveAnalysisReport(BaseModel):
    """Aggregated report from all L3 adaptive analyzers.

    Published to the event bus after all five analyzers complete. Contains
    the final MCAV score from the DCA aggregator.

    Fields:
        request_id: Links this report to the RequestContext.
        timestamp: When adaptive analysis completed.
        analyzer_results: Individual results from all analyzers.
        mcav_score: Mature Context Antigen Value from DCA (0.0-1.0).
        should_block: Whether the MCAV exceeds the threat threshold.
        is_novel_attack: True if adaptive caught something innate missed.
        total_latency_ms: Total adaptive layer execution time.
    """
    request_id: str = Field(description="Request ID from RequestContext")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp of analysis completion",
    )
    analyzer_results: list[AdaptiveAnalysisResult] = Field(
        default_factory=list,
        description="Individual results from all analyzers",
    )
    mcav_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="DCA Mature Context Antigen Value (>0.7 anomalous, >0.9 threat)",
    )
    should_block: bool = Field(
        default=False,
        description="Whether MCAV exceeds the configured threat threshold",
    )
    is_novel_attack: bool = Field(
        default=False,
        description="True if adaptive detected a threat innate missed (triggers antibody generation)",
    )
    total_latency_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="Total adaptive layer execution time in milliseconds",
    )

    @property
    def all_dca_signals(self) -> list[DCASignal]:
        """Collect all DCA signals from all analyzer results."""
        signals = []
        for result in self.analyzer_results:
            signals.extend(result.dca_signals)
        return signals
